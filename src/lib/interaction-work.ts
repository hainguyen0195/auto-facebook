import { z } from "zod";
import type {
  FacebookConnection,
  Interaction,
  FacebookAccount,
  Task,
} from "@prisma/client";
import { AppError, assertFound } from "./errors";
import { workspaceTransaction, type Tx } from "./service";
import {
  AUTOMATIC_ATTEMPT_MS,
  automaticFailureState,
} from "./automatic-policy";
import { dayBounds } from "./utils";
import { isQuietHour } from "./task-policy";
import { canonicalFacebookPost } from "./facebook-post-url";

type Job = Interaction & { account: FacebookAccount; sourceTask: Task | null };
const include = { account: true, sourceTask: true } as const;

function currentStep(row: Interaction) {
  return row.kind === "REACTION" ||
    (row.kind === "COMBINED" && row.reactionState !== "COMPLETED")
    ? "REACTION"
    : "COMMENT";
}
function stepData(row: Interaction, state: string) {
  return currentStep(row) === "REACTION"
    ? { reactionState: state }
    : { commentState: state };
}

async function pacingWait(
  tx: Pick<Tx, "interaction">,
  workspaceId: string,
  gapMinutes: number,
  now: Date,
  excludeId?: string,
) {
  const where = {
    workspaceId,
    executionMode: "AUTOMATIC",
    ...(excludeId ? { id: { not: excludeId } } : {}),
  };
  if (
    await tx.interaction.count({ where: { ...where, status: "IN_PROGRESS" } })
  )
    return "Đang có tương tác khác chạy; chờ hoàn tất trước khi đến lượt.";
  const since = new Date(now.getTime() - gapMinutes * 60_000);
  if (
    await tx.interaction.count({
      where: {
        ...where,
        OR: [{ startedAt: { gt: since } }, { leaseAt: { gt: since } }],
      },
    })
  )
    return `Chờ khoảng cách chung ${gapMinutes} phút giữa các bước tương tác, kể cả khác tài khoản.`;
  return null;
}

export async function interactionWait(
  tx: Pick<Tx, "interaction" | "task" | "autoInteractionSetting">,
  row: Job,
  connection: FacebookConnection | null,
  now: Date,
) {
  const config = await tx.autoInteractionSetting.findUnique({
    where: { workspaceId: row.workspaceId },
  });
  if (row.autoGenerated && !config?.enabled)
    return "Tự tương tác bài mới đang tắt.";
  if (!connection?.interactionEnabled)
    return "Chưa bật Cho phép tự tương tác cho tài khoản này.";
  if (
    connection.state !== "READY" ||
    !connection.confirmedIdentityHash ||
    connection.identityHash !== connection.confirmedIdentityHash
  )
    return "Cần kiểm tra và xác nhận đúng tài khoản Facebook.";
  if (row.account.status !== "ACTIVE" || row.account.archivedAt)
    return "Tài khoản đang tạm dừng hoặc đã lưu trữ.";
  if (
    !row.sourceTask ||
    row.sourceTask.status !== "PUBLISHED" ||
    canonicalFacebookPost(row.sourceTask.resultUrl || "")?.postKey !==
      row.postKey
  )
    return "Bài nguồn hoặc link đã thay đổi; cần kiểm tra lại.";
  if (
    await tx.task.count({
      where: {
        workspaceId: row.workspaceId,
        accountId: row.accountId,
        status: "BLOCKED",
        automaticPhase: "NEEDS_REVIEW",
        archivedAt: null,
      },
    })
  )
    return "Tài khoản đang chờ kiểm tra kết quả một bài đăng trước.";
  const hour = Number(
    new Intl.DateTimeFormat("en-GB", {
      timeZone: "Asia/Bangkok",
      hour: "2-digit",
      hourCycle: "h23",
    }).format(now),
  );
  if (
    isQuietHour(
      hour,
      row.account.quietStart,
      row.account.quietEnd,
      row.account.quietHoursEnabled,
    )
  )
    return "Đang trong giờ nghỉ của tài khoản.";
  const where = {
    workspaceId: row.workspaceId,
    accountId: row.accountId,
    executionMode: "AUTOMATIC",
    id: { not: row.id },
  };
  if (
    await tx.interaction.count({ where: { ...where, status: "NEEDS_REVIEW" } })
  )
    return "Đang chờ kiểm tra một tương tác trước của tài khoản; lịch đăng bài vẫn độc lập.";
  const bounds = dayBounds(now);
  if (
    (await tx.interaction.count({
      where: {
        ...where,
        startedAt: { gte: bounds.start, lt: bounds.end },
        status: { not: "SKIPPED" },
      },
    })) >= connection.interactionDailyLimit
  )
    return "Đã đạt giới hạn tương tác hôm nay.";
  const pacing = await pacingWait(
    tx,
    row.workspaceId,
    config?.gapMinutes || 5,
    now,
    row.status === "IN_PROGRESS" ? row.id : undefined,
  );
  if (pacing) return pacing;
  if (
    connection.interactionIntervalMinutes &&
    (await tx.interaction.count({
      where: {
        ...where,
        startedAt: {
          gt: new Date(
            now.getTime() - connection.interactionIntervalMinutes * 60_000,
          ),
        },
        status: { not: "SKIPPED" },
      },
    }))
  )
    return `Chờ khoảng cách ${connection.interactionIntervalMinutes} phút giữa các tương tác.`;
  return null;
}

export async function claimInteraction(
  tx: Tx,
  deviceId: string,
  workspaceId: string,
  now = new Date(),
) {
  const config = await tx.autoInteractionSetting.findUnique({
    where: { workspaceId },
  });
  if (await pacingWait(tx, workspaceId, config?.gapMinutes || 5, now))
    return null;
  const connections = await tx.facebookConnection.findMany({
    where: { workspaceId, deviceId, state: "READY", interactionEnabled: true },
  });
  let cursor: string | undefined;
  for (;;) {
    const rows = await tx.interaction.findMany({
      where: {
        workspaceId,
        archivedAt: null,
        accountId: { in: connections.map((c) => c.accountId) },
        executionMode: "AUTOMATIC",
        status: { in: ["APPROVED", "RETRY_WAIT"] },
        scheduledAt: { lte: now },
        OR: [{ nextAttemptAt: null }, { nextAttemptAt: { lte: now } }],
      },
      include,
      orderBy: [{ scheduledAt: "asc" }, { id: "asc" }],
      take: 100,
      ...(cursor ? { cursor: { id: cursor }, skip: 1 } : {}),
    });
    for (const row of rows) {
      const connection = connections.find(
        (c) => c.accountId === row.accountId,
      )!;
      if (await interactionWait(tx, row, connection, now)) continue;
      const runId = randomUUID();
      await tx.interaction.update({
        where: { id: row.id },
        data: {
          status: "IN_PROGRESS",
          ...stepData(row, "PREPARING"),
          phase: "PREPARING",
          desktopDeviceId: deviceId,
          runId,
          leaseAt: now,
          startedAt: now,
          attempts: { increment: 1 },
          nextAttemptAt: null,
          version: { increment: 1 },
        },
      });
      await tx.interactionEvent.create({
        data: {
          interactionId: row.id,
          runId,
          fromStatus: row.status,
          toStatus: "IN_PROGRESS",
          note: `${currentStep(row) === "REACTION" ? "Thả cảm xúc" : "Bình luận"} · Bắt đầu lượt ${row.attempts + 1}/3.`,
        },
      });
      return {
        type: "INTERACTION" as const,
        id: row.id,
        runId,
        attemptDeadlineAt: new Date(
          now.getTime() + AUTOMATIC_ATTEMPT_MS,
        ).toISOString(),
        account: { id: row.accountId, name: row.account.name },
        identityHash: connection.confirmedIdentityHash!,
        targetUrl: row.postUrl,
        content: row.content,
        // Serialize a combined job as two ordinary, independently acknowledged runs.
        interactionKind:
          row.kind === "COMBINED"
            ? currentStep(row)
            : (row.kind as "COMMENT" | "BUMP" | "REACTION"),
        reaction: row.reaction,
      };
    }
    if (rows.length < 100) break;
    cursor = rows[rows.length - 1].id;
  }
  return null;
}

export async function armInteraction(
  deviceId: string,
  workspaceId: string,
  id: string,
  runId: string,
  targetUrl: string,
) {
  if (process.env.NHIPDANG_AUTOMATIC_INTERACTIONS === "0")
    throw new AppError(409, "Tự tương tác đang tắt trên máy chủ.");
  return workspaceTransaction(workspaceId, async (tx) => {
    const row = assertFound(
      await tx.interaction.findFirst({
        where: {
          id,
          workspaceId,
          desktopDeviceId: deviceId,
          runId,
          executionMode: "AUTOMATIC",
        },
        include,
      }),
    );
    const device = await tx.desktopDevice.findUniqueOrThrow({
      where: { id: deviceId },
    });
    const connection = await tx.facebookConnection.findUnique({
      where: { accountId: row.accountId },
    });
    if (
      row.status !== "IN_PROGRESS" ||
      row.phase !== "PREPARING" ||
      row.postUrl !== targetUrl ||
      !row.startedAt ||
      Date.now() >= row.startedAt.getTime() + AUTOMATIC_ATTEMPT_MS ||
      !row.leaseAt ||
      Date.now() - row.leaseAt.getTime() >= 5 * 60_000 ||
      device.paused ||
      device.revokedAt ||
      !device.lastSeenAt ||
      Date.now() - device.lastSeenAt.getTime() >= 45_000 ||
      connection?.deviceId !== deviceId
    )
      throw new AppError(
        409,
        "Tương tác đã dừng, hết hạn hoặc đổi đích. Không được thực hiện.",
      );
    const reason = await interactionWait(tx, row, connection, new Date());
    if (reason) throw new AppError(409, reason);
    if (
      await tx.task.count({
        where: {
          workspaceId,
          desktopDeviceId: deviceId,
          status: "IN_PROGRESS",
          executionMode: "AUTOMATIC",
        },
      })
    )
      throw new AppError(
        409,
        "Máy đang đăng bài; không được tương tác đồng thời.",
      );
    await tx.interaction.update({
      where: { id },
      data: {
        phase: "SUBMITTING",
        ...stepData(row, "SUBMITTING"),
        leaseAt: new Date(),
      },
    });
    return { allowed: true };
  });
}

export const interactionResultSchema = z.object({
  runId: z.uuid(),
  outcome: z.enum([
    "COMPLETED",
    "ALREADY_DONE",
    "FAILED",
    "UNCERTAIN",
    "LOGIN_REQUIRED",
    "CHALLENGE",
  ]),
  message: z.string().max(2000),
  issueCode: z.literal("TARGET_UNAVAILABLE").optional(),
  failure: z
    .object({
      stage: z.string().max(120),
      submitAttempted: z.boolean(),
      code: z.enum(["TIMEOUT", "NETWORK", "OTHER"]),
    })
    .optional(),
});
export async function finishInteraction(
  deviceId: string,
  workspaceId: string,
  id: string,
  input: z.infer<typeof interactionResultSchema>,
) {
  return workspaceTransaction(workspaceId, async (tx) => {
    const row = assertFound(
      await tx.interaction.findFirst({
        where: { id, workspaceId, executionMode: "AUTOMATIC" },
      }),
    );
    if (
      row.desktopDeviceId !== deviceId ||
      row.runId !== input.runId ||
      row.status !== "IN_PROGRESS"
    )
      return { ok: true, stale: true };
    if (
      (input.outcome === "COMPLETED" && row.phase !== "SUBMITTING") ||
      (input.outcome === "ALREADY_DONE" && row.phase !== "PREPARING")
    )
      throw new AppError(409, "Kết quả không phù hợp giai đoạn tương tác.");
    const success = ["COMPLETED", "ALREADY_DONE"].includes(input.outcome);
    const moreSteps =
      success && row.kind === "COMBINED" && currentStep(row) === "REACTION";
    const disabled =
      row.autoGenerated &&
      !(await tx.autoInteractionSetting.findUnique({ where: { workspaceId } }))
        ?.enabled;
    const config =
      moreSteps && !disabled
        ? await tx.autoInteractionSetting.findUnique({ where: { workspaceId } })
        : null;
    const safe =
      input.outcome === "FAILED" &&
      input.failure?.submitAttempted === false &&
      row.phase === "PREPARING";
    const unavailable =
      safe &&
      (input.issueCode === "TARGET_UNAVAILABLE" ||
        (input.failure?.stage === "kiểm tra phiên và mở bài" &&
          input.message.includes(
            "Bài không thể truy cập bằng tài khoản đã chọn; kiểm tra quyền nhóm hoặc bài đã bị xóa.",
          )));
    const retry =
      safe && !unavailable
        ? automaticFailureState(row.attempts, input.failure!.code !== "OTHER")
        : null;
    const status =
      unavailable || (disabled && safe)
        ? "SKIPPED"
        : success
          ? moreSteps
            ? disabled
              ? "SKIPPED"
              : "APPROVED"
            : "COMPLETED"
          : retry
            ? retry.automaticPhase === "RETRY_WAIT"
              ? "RETRY_WAIT"
              : "FAILED"
            : "NEEDS_REVIEW";
    await tx.interaction.update({
      where: { id },
      data: {
        status,
        ...(unavailable
          ? { skipReason: "TARGET_UNAVAILABLE", unavailableAt: new Date() }
          : {}),
        ...stepData(
          row,
          success
            ? "COMPLETED"
            : status === "SKIPPED"
              ? "SKIPPED"
              : retry
                ? status === "RETRY_WAIT"
                  ? "PENDING"
                  : "FAILED"
                : "NEEDS_REVIEW",
        ),
        ...(status === "SKIPPED" &&
        row.kind === "COMBINED" &&
        currentStep(row) === "REACTION"
          ? { commentState: "SKIPPED" }
          : {}),
        ...(moreSteps && disabled ? { commentState: "SKIPPED" } : {}),
        phase:
          moreSteps && !disabled
            ? "NONE"
            : success || status === "SKIPPED"
              ? "DONE"
              : retry?.automaticPhase || "NEEDS_REVIEW",
        nextAttemptAt:
          moreSteps && !disabled
            ? new Date(Date.now() + (config?.gapMinutes || 5) * 60_000)
            : status === "RETRY_WAIT"
              ? retry?.nextAttemptAt || null
              : null,
        note: unavailable
          ? `Link không khả dụng với tài khoản được giao. Đã bỏ qua bài, không tự thử lại hoặc đổi tài khoản. ${input.message}`
          : moreSteps
            ? `${input.message} ${disabled ? "Đã tắt tự chạy; không bình luận tiếp." : "Chờ bước bình luận."}`
            : input.message,
        completedAt: success && !moreSteps ? new Date() : null,
        leaseAt: new Date(),
        ...(moreSteps ? { attempts: 0 } : {}),
        resultSource: "DESKTOP",
        version: { increment: 1 },
      },
    });
    await tx.interactionEvent.create({
      data: {
        interactionId: id,
        runId: input.runId,
        fromStatus: row.status,
        toStatus: status,
        note: `${currentStep(row) === "REACTION" ? "Thả cảm xúc" : "Bình luận"} · Lượt ${row.attempts}/3 · ${input.failure?.stage || "kết quả"} · ${input.message}`,
      },
    });
    if (["LOGIN_REQUIRED", "CHALLENGE"].includes(input.outcome))
      await tx.facebookConnection.updateMany({
        where: { workspaceId, deviceId, accountId: row.accountId },
        data: {
          state: input.outcome,
          confirmedIdentityHash: null,
          interactionEnabled: false,
          automationEnabled: false,
          message: input.message,
        },
      });
    return { ok: true };
  });
}

export async function recoverInteractions(
  tx: Tx,
  workspaceId: string,
  now: Date,
) {
  const rows = await tx.interaction.findMany({
    where: {
      workspaceId,
      executionMode: "AUTOMATIC",
      status: "IN_PROGRESS",
      leaseAt: { lt: new Date(now.getTime() - 5 * 60_000) },
    },
  });
  for (const row of rows) {
    const retry =
      row.phase === "PREPARING"
        ? automaticFailureState(row.attempts, true, now)
        : null;
    const status = retry
      ? retry.automaticPhase === "RETRY_WAIT"
        ? "RETRY_WAIT"
        : "FAILED"
      : "NEEDS_REVIEW";
    const note = retry
      ? "Máy bị gián đoạn trước khi cấp quyền tương tác; áp dụng giới hạn thử lại."
      : "Gián đoạn sau khi cấp quyền tương tác. Kiểm tra Facebook, không tự thực hiện lại.";
    await tx.interaction.update({
      where: { id: row.id },
      data: {
        status,
        ...stepData(
          row,
          retry
            ? status === "RETRY_WAIT"
              ? "PENDING"
              : "FAILED"
            : "NEEDS_REVIEW",
        ),
        phase: retry?.automaticPhase || "NEEDS_REVIEW",
        nextAttemptAt: retry?.nextAttemptAt || null,
        note,
        version: { increment: 1 },
      },
    });
    await tx.interactionEvent.create({
      data: {
        interactionId: row.id,
        runId: row.runId,
        fromStatus: "IN_PROGRESS",
        toStatus: status,
        note,
      },
    });
  }
  return rows.length;
}

export const interactionSettingsSchema = z.object({
  enabled: z.boolean(),
  dailyLimit: z.number().int().min(1).max(100).default(10),
  intervalMinutes: z.number().int().min(1).max(1440).default(5),
});
export async function updateInteractionSettings(
  workspaceId: string,
  accountId: string,
  input: z.infer<typeof interactionSettingsSchema>,
) {
  return workspaceTransaction(workspaceId, async (tx) => {
    const connection = assertFound(
      await tx.facebookConnection.findFirst({
        where: { accountId, workspaceId },
        include: { account: true },
      }),
    );
    if (
      input.enabled &&
      (connection.state !== "READY" ||
        !connection.confirmedIdentityHash ||
        connection.identityHash !== connection.confirmedIdentityHash ||
        connection.account.status !== "ACTIVE" ||
        connection.account.archivedAt)
    )
      throw new AppError(
        409,
        "Xác nhận đúng Facebook đang hoạt động trước khi bật tự tương tác.",
      );
    return tx.facebookConnection.update({
      where: { id: connection.id },
      data: {
        interactionEnabled: input.enabled,
        interactionDailyLimit: input.dailyLimit,
        interactionIntervalMinutes: input.intervalMinutes,
      },
    });
  });
}
