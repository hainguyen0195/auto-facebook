import { randomInt } from "node:crypto";
import { z } from "zod";
import type { AutoInteractionSetting, Prisma } from "@prisma/client";
import { db } from "./db";
import { AppError } from "./errors";
import { workspaceTransaction, type Tx } from "./service";
import { canonicalFacebookPost } from "./facebook-post-url";
import { dayBounds, dateKey } from "./utils";

function commentTemplates(content: string) {
  return [
    ...new Set(
      content
        .split(/\r?\n/)
        .map((line) => line.trim())
        .filter(Boolean),
    ),
  ];
}

export const autoInteractionSchema = z
  .object({
    enabled: z.boolean(),
    mode: z.enum(["COMMENT", "REACTION", "COMBINED"]),
    content: z.string().trim().max(4000).default("Up"),
    reactions: z.array(z.enum(["LIKE", "LOVE", "HAHA"])).max(3),
    includeToday: z.boolean().default(false),
    selectedDays: z
      .array(z.enum(["YESTERDAY", "TODAY"]))
      .max(2)
      .default([]),
    gapMinutes: z.number().int().min(1).max(1440).default(5),
    version: z.number().int().nonnegative(),
  })
  .superRefine((v, ctx) => {
    if (v.enabled && v.mode !== "REACTION" && !v.content)
      ctx.addIssue({
        code: "custom",
        path: ["content"],
        message: "Nhập nội dung bình luận.",
      });
    if (commentTemplates(v.content).length > 50)
      ctx.addIssue({
        code: "custom",
        path: ["content"],
        message: "Nhập tối đa 50 mẫu bình luận, mỗi dòng một mẫu.",
      });
    if (v.enabled && v.mode !== "COMMENT" && !v.reactions.length)
      ctx.addIssue({
        code: "custom",
        path: ["reactions"],
        message: "Chọn ít nhất một cảm xúc.",
      });
  });

export const autoInteractionDefaults = {
  enabled: false,
  mode: "COMBINED",
  content: "Up",
  reactions: ["LIKE", "LOVE", "HAHA"],
  startsAt: null,
  backfillDays: [],
  gapMinutes: 5,
  version: 0,
};

function sourceWindow(config: AutoInteractionSetting): Prisma.TaskWhereInput {
  return {
    OR: [
      ...(config.startsAt ? [{ recordedAt: { gte: config.startsAt } }] : []),
      ...config.backfillDays.map((start) => ({
        recordedAt: { gte: start, lt: new Date(start.getTime() + 86_400_000) },
      })),
    ],
  };
}

async function eligibleActors(
  tx: Pick<Tx, "facebookConnection">,
  workspaceId: string,
) {
  const connections = await tx.facebookConnection.findMany({
    where: {
      workspaceId,
      state: "READY",
      interactionEnabled: true,
      account: { status: "ACTIVE", archivedAt: null },
      device: { revokedAt: null },
    },
    include: {
      account: { include: { memberships: { select: { groupId: true } } } },
    },
    orderBy: { accountId: "asc" },
  });
  return connections.filter(
    (c) =>
      c.confirmedIdentityHash && c.identityHash === c.confirmedIdentityHash,
  );
}

export async function autoInteractionStatus(
  workspaceId: string,
  now = new Date(),
) {
  const [settings, actors, counts] = await Promise.all([
    db.autoInteractionSetting.findUnique({ where: { workspaceId } }),
    eligibleActors(db, workspaceId),
    db.interaction.groupBy({
      by: ["status"],
      where: { workspaceId, autoGenerated: true, archivedAt: null },
      _count: true,
    }),
  ]);
  const waitingSources =
    settings?.enabled && settings.startsAt
      ? await db.task.count({
          where: {
            workspaceId,
            status: "PUBLISHED",
            archivedAt: null,
            ...sourceWindow(settings),
            sourceInteractions: { none: {} },
          },
        })
      : 0;
  const today = dayBounds(now).start;
  const dayOptions = await Promise.all(
    (["YESTERDAY", "TODAY"] as const).map(async (value) => {
      const start = new Date(
        today.getTime() - (value === "YESTERDAY" ? 86_400_000 : 0),
      );
      const where = {
        workspaceId,
        status: "PUBLISHED" as const,
        archivedAt: null,
        recordedAt: { gte: start, lt: new Date(start.getTime() + 86_400_000) },
      };
      const [total, waiting] = await Promise.all([
        db.task.count({ where }),
        db.task.count({
          where: { ...where, sourceInteractions: { none: {} } },
        }),
      ]);
      return { value, date: dateKey(start), total, waiting };
    }),
  );
  return {
    settings: settings || autoInteractionDefaults,
    actors: actors.map((c) => ({ id: c.accountId, name: c.account.name })),
    counts: Object.fromEntries(counts.map((r) => [r.status, r._count])),
    waitingSources,
    dayOptions,
  };
}

// Called under the workspace lock, so scanners and form saves cannot assign twice.
export async function enqueueAutoInteractions(
  tx: Tx,
  config: AutoInteractionSetting,
  now = new Date(),
) {
  if (
    !config.enabled ||
    !config.startsAt ||
    process.env.NHIPDANG_AUTOMATIC_INTERACTIONS === "0"
  )
    return 0;
  const actors = await eligibleActors(tx, config.workspaceId);
  if (!actors.length) return 0;
  let created = 0,
    cursor: string | undefined,
    lastActorId = config.lastActorId,
    lastComment = config.lastComment;
  const templates = commentTemplates(config.content);
  const lastQueued = await tx.interaction.findFirst({
    where: {
      workspaceId: config.workspaceId,
      executionMode: "AUTOMATIC",
      status: { in: ["APPROVED", "RETRY_WAIT", "IN_PROGRESS"] },
    },
    orderBy: { scheduledAt: "desc" },
  });
  const gap = config.gapMinutes * 60_000;
  let slot = Math.max(
    now.getTime(),
    lastQueued
      ? Math.max(
          lastQueued.scheduledAt.getTime(),
          lastQueued.nextAttemptAt?.getTime() || 0,
        ) +
          gap *
            (lastQueued.kind === "COMBINED" &&
            lastQueued.reactionState !== "COMPLETED"
              ? 2
              : 1)
      : 0,
  );
  for (;;) {
    const sources = await tx.task.findMany({
      where: {
        workspaceId: config.workspaceId,
        status: "PUBLISHED",
        archivedAt: null,
        ...sourceWindow(config),
        resultUrl: { not: null },
        sourceInteractions: { none: {} },
        ...(cursor ? { id: { gt: cursor } } : {}),
      },
      orderBy: { id: "asc" },
      take: 100,
    });
    if (!sources.length) break;
    const targets = sources.map((s) =>
      canonicalFacebookPost(s.resultUrl || ""),
    );
    const existing = new Set(
      (
        await tx.interaction.findMany({
          where: {
            workspaceId: config.workspaceId,
            postKey: { in: targets.flatMap((t) => (t ? [t.postKey] : [])) },
          },
          select: { postKey: true },
        })
      ).map((i) => i.postKey),
    );
    for (let index = 0; index < sources.length; index++) {
      const source = sources[index],
        target = targets[index];
      if (!target || existing.has(target.postKey)) continue;
      const start =
        (actors.findIndex((a) => a.accountId === lastActorId) + 1) %
        actors.length;
      const actor = Array.from(
        { length: actors.length },
        (_, n) => actors[(start + n) % actors.length],
      ).find(
        (a) =>
          a.accountId !== source.accountId &&
          (!source.groupId ||
            a.account.memberships.some((m) => m.groupId === source.groupId)),
      );
      if (!actor) continue;
      const reaction =
        config.mode !== "COMMENT"
          ? config.reactions[randomInt(config.reactions.length)]
          : null;
      const choices =
        templates.length > 1
          ? templates.filter((text) => text !== lastComment)
          : templates;
      const content =
        config.mode === "REACTION" ? "" : choices[randomInt(choices.length)];
      const job = await tx.interaction.create({
        data: {
          workspaceId: config.workspaceId,
          sourceTaskId: source.id,
          accountId: actor.accountId,
          ...target,
          executionMode: "AUTOMATIC",
          autoGenerated: true,
          kind: config.mode,
          content,
          reaction,
          reactionState: config.mode === "COMMENT" ? "NONE" : "PENDING",
          commentState: config.mode === "REACTION" ? "NONE" : "PENDING",
          status: "APPROVED",
          scheduledAt: new Date(slot),
          note: "Tự nhận bài theo thiết lập đã bật; mỗi bài một tài khoản khác phụ trách.",
        },
      });
      await tx.interactionEvent.create({
        data: {
          interactionId: job.id,
          fromStatus: "PLANNED",
          toStatus: "APPROVED",
          note: `Tự giao cho ${actor.account.name}; giữ nguyên nội dung và cảm xúc của công việc này khi thử lại.`,
        },
      });
      existing.add(target.postKey);
      slot += gap * (config.mode === "COMBINED" ? 2 : 1);
      lastActorId = actor.accountId;
      if (content) lastComment = content;
      if (++created >= 100) break;
    }
    if (created >= 100 || sources.length < 100) break;
    cursor = sources[sources.length - 1].id;
  }
  if (created)
    await tx.autoInteractionSetting.update({
      where: { workspaceId: config.workspaceId },
      data: { lastActorId, lastComment },
    });
  return created;
}

export async function saveAutoInteractions(
  workspaceId: string,
  input: z.infer<typeof autoInteractionSchema>,
  now = new Date(),
) {
  return workspaceTransaction(workspaceId, async (tx) => {
    const previous = await tx.autoInteractionSetting.findUnique({
      where: { workspaceId },
    });
    if ((previous?.version || 0) !== input.version)
      throw new AppError(409, "Thiết lập đã thay đổi. Tải lại trước khi lưu.");
    let startsAt = previous?.startsAt || null;
    if (input.enabled && !previous?.enabled)
      startsAt = input.includeToday ? dayBounds(now).start : now;
    else if (
      input.enabled &&
      input.includeToday &&
      (!startsAt || dayBounds(now).start < startsAt)
    )
      startsAt = dayBounds(now).start;
    const today = dayBounds(now).start;
    const backfillDays = input.enabled
      ? [
          ...new Map([
            ...(previous?.enabled ? previous.backfillDays : []).map(
              (day) => [day.toISOString(), day] as const,
            ),
            ...input.selectedDays.map((day) => {
              const start = new Date(
                today.getTime() - (day === "YESTERDAY" ? 86_400_000 : 0),
              );
              return [start.toISOString(), start] as const;
            }),
          ]).values(),
        ]
      : previous?.backfillDays || [];
    const data = {
      enabled: input.enabled,
      mode: input.mode,
      content: commentTemplates(input.content).join("\n"),
      reactions: [...new Set(input.reactions)],
      startsAt,
      backfillDays,
      gapMinutes: input.gapMinutes,
      version: (previous?.version || 0) + 1,
    };
    const settings = await tx.autoInteractionSetting.upsert({
      where: { workspaceId },
      create: { workspaceId, ...data },
      update: data,
    });
    if (previous && previous.gapMinutes !== settings.gapMinutes) {
      const pending = await tx.interaction.findMany({
        where: {
          workspaceId,
          autoGenerated: true,
          status: { in: ["APPROVED", "RETRY_WAIT", "PLANNED"] },
        },
        orderBy: [{ scheduledAt: "asc" }, { id: "asc" }],
      });
      const active = await tx.interaction.count({
        where: {
          workspaceId,
          executionMode: "AUTOMATIC",
          status: "IN_PROGRESS",
        },
      });
      const gap = settings.gapMinutes * 60_000;
      let slot = now.getTime() + (active ? gap : 0);
      for (const row of pending) {
        slot = Math.max(slot, row.nextAttemptAt?.getTime() || 0);
        await tx.interaction.update({
          where: { id: row.id },
          data: {
            scheduledAt: new Date(slot),
            version: { increment: 1 },
          },
        });
        slot +=
          gap *
          (row.kind === "COMBINED" && row.reactionState !== "COMPLETED"
            ? 2
            : 1);
      }
    }
    if (!input.enabled) {
      const rows = await tx.interaction.findMany({
        where: {
          workspaceId,
          autoGenerated: true,
          OR: [
            { status: { in: ["APPROVED", "RETRY_WAIT", "PLANNED"] } },
            { status: "IN_PROGRESS", phase: "PREPARING" },
          ],
        },
      });
      for (const row of rows) {
        await tx.interaction.update({
          where: { id: row.id },
          data: {
            status: "SKIPPED",
            phase: "DONE",
            nextAttemptAt: null,
            version: { increment: 1 },
            reactionState: ["NONE", "COMPLETED"].includes(row.reactionState)
              ? row.reactionState
              : "SKIPPED",
            commentState: ["NONE", "COMPLETED"].includes(row.commentState)
              ? row.commentState
              : "SKIPPED",
            note: "Đã tắt tự tương tác bài mới; dừng các bước chưa chạy.",
          },
        });
        await tx.interactionEvent.create({
          data: {
            interactionId: row.id,
            fromStatus: row.status,
            toStatus: "SKIPPED",
            note: "Dừng các bước chưa chạy khi tắt tự tương tác bài mới.",
          },
        });
      }
    }
    const queued = await enqueueAutoInteractions(tx, settings, now);
    return { settings, queued };
  });
}

export async function scanAutoInteractions() {
  const configs = await db.autoInteractionSetting.findMany({
    where: { enabled: true },
  });
  let queued = 0;
  for (const config of configs)
    queued += await workspaceTransaction(config.workspaceId, async (tx) => {
      const current = await tx.autoInteractionSetting.findUniqueOrThrow({
        where: { workspaceId: config.workspaceId },
      });
      return enqueueAutoInteractions(tx, current);
    });
  return queued;
}
