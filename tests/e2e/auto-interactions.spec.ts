import { expect, test, type Page } from "@playwright/test";

async function mockInteractions(page: Page, savedDays: string[] = []) {
  let settings = {
    enabled: false,
    mode: "COMBINED",
    content: "Fixture comment",
    reactions: ["LIKE"],
    startsAt: null as string | null,
    backfillDays: savedDays,
    gapMinutes: 5,
    version: 0,
  };
  const dayOptions = [
    { value: "YESTERDAY", date: "2026-11-10", total: 288, waiting: 248 },
    { value: "TODAY", date: "2026-11-11", total: 0, waiting: 0 },
  ];
  const saves: { selectedDays: string[] }[] = [];
  await page.route("**/api/v1/auto-interactions", async (route) => {
    if (route.request().method() === "PATCH") {
      const body = route.request().postDataJSON();
      saves.push(body);
      settings = {
        ...settings,
        ...body,
        startsAt: "2026-11-11T03:00:00.000Z",
        backfillDays: dayOptions
          .filter((day) => body.selectedDays.includes(day.value))
          .map((day) => `${day.date}T00:00:00+07:00`),
        version: settings.version + 1,
      };
      await route.fulfill({ json: { settings, queued: 0 } });
      return;
    }
    await route.fulfill({
      json: { settings, actors: [], counts: {}, waitingSources: 0, dayOptions },
    });
  });
  await page.route("**/api/v1/accounts", (route) =>
    route.fulfill({ json: [] }),
  );
  await page.route("**/api/v1/interactions?**", (route) =>
    route.fulfill({
      json: { items: [], total: 0, unavailableCount: 0, page: 1, size: 30 },
    }),
  );
  return saves;
}

test("keeps yesterday selected after starting, saving and reloading", async ({
  page,
}) => {
  const saves = await mockInteractions(page);
  await page.goto("/interactions");
  const yesterday = page.getByRole("checkbox", { name: /Bài hôm qua/ });
  await yesterday.check();
  await page.getByRole("button", { name: "Lưu và bật tự chạy" }).click();
  await expect(page.getByRole("button", { name: "Tắt tự chạy" })).toBeVisible();
  await expect(yesterday).toBeChecked();
  await page
    .getByRole("button", { name: "Lưu thiết lập", exact: true })
    .click();
  await expect.poll(() => saves.length).toBe(2);
  expect(saves.map((save) => save.selectedDays)).toEqual([
    ["YESTERDAY"],
    ["YESTERDAY"],
  ]);
  await page.reload();
  await expect(yesterday).toBeChecked();
  await expect(
    page.getByRole("checkbox", { name: /Bài hôm nay/ }),
  ).not.toBeChecked();
});

test("matches saved UTC dates to the corresponding UTC+7 day", async ({
  page,
}) => {
  await mockInteractions(page, ["2026-11-09T17:00:00.000Z"]);
  await page.goto("/interactions");
  await expect(
    page.getByRole("checkbox", { name: /Bài hôm qua/ }),
  ).toBeChecked();
  await expect(
    page.getByRole("checkbox", { name: /Bài hôm nay/ }),
  ).not.toBeChecked();
});

for (const width of [1280, 390]) {
  test(`confirms single and yesterday deletions and retains running work at ${width}px`, async ({
    page,
  }) => {
    await page.setViewportSize({ width, height: 900 });
    await mockInteractions(page);
    const row = (id: string, status: string, scheduledAt: string) => ({
      id,
      status,
      scheduledAt,
      accountId: "fixture",
      account: { name: "Fixture account", profileName: "Fixture" },
      kind: "COMMENT",
      content: id,
      postUrl: `https://www.facebook.com/groups/fixture/posts/${id.replaceAll(" ", "-")}${"1".repeat(30)}`,
      reactionState: "NONE",
      commentState: "SKIPPED",
      autoGenerated: false,
      executionMode: "MANUAL",
      resultSource: "USER",
      attempts: 0,
      note: "",
      nextAttemptAt: null,
    });
    let rows = [
      row("Yesterday item", "SKIPPED", "2026-11-10T12:00:00+07:00"),
      row("Running item", "IN_PROGRESS", "2026-11-10T13:00:00+07:00"),
      row("Today item", "SKIPPED", "2026-11-11T12:00:00+07:00"),
    ];
    let hiddenYesterday = 20;
    const requests: { method: string; date?: string }[] = [];
    await page.route("**/api/v1/interactions**", async (route) => {
      const request = route.request();
      if (request.method() === "DELETE") {
        requests.push({ method: "DELETE" });
        rows = rows.filter((item) => item.id !== "Yesterday item");
        await route.fulfill({ json: { archived: 1 } });
      } else if (request.method() === "POST") {
        requests.push({ method: "POST", date: request.postDataJSON().date });
        rows = rows.filter(
          (item) => item.status === "IN_PROGRESS" || item.id === "Today item",
        );
        const archived = hiddenYesterday;
        hiddenYesterday = 0;
        await route.fulfill({ json: { archived, running: 1 } });
      } else {
        await route.fulfill({
          json: {
            items: rows,
            total: hiddenYesterday + rows.length,
            size: 20,
            page: 1,
            unavailableCount: 0,
            yesterdayDate: "2026-11-10",
            yesterdayCount:
              hiddenYesterday +
              (rows.some((item) => item.id === "Yesterday item") ? 1 : 0),
            yesterdayRunning: 1,
          },
        });
      }
    });
    await page.goto("/interactions");
    const oldCard = page
      .locator(".interaction-card")
      .filter({ hasText: "Yesterday item" });
    const runningCard = page
      .locator(".interaction-card")
      .filter({ hasText: "Running item" });
    await expect(
      runningCard.getByRole("button", { name: "Xóa", exact: true }),
    ).toBeDisabled();
    await oldCard.getByRole("button", { name: "Xóa", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await expect(dialog).toContainText("Facebook được giữ nguyên");
    expect(
      await dialog.evaluate(
        (element) => element.scrollWidth <= element.clientWidth,
      ),
    ).toBe(true);
    expect(requests).toHaveLength(0);
    await dialog.getByRole("button", { name: "Hủy", exact: true }).click();
    await expect(oldCard).toBeVisible();
    await oldCard.getByRole("button", { name: "Xóa", exact: true }).click();
    await dialog.getByRole("button", { name: "Xác nhận xóa" }).click();
    await expect(oldCard).toHaveCount(0);
    await page.getByRole("button", { name: "Xóa tất cả hôm qua" }).click();
    await expect(dialog).toContainText("Xóa 20 công việc");
    await expect(dialog).toContainText("Giữ lại 1 công việc đang chạy");
    await dialog.getByRole("button", { name: "Xác nhận xóa" }).click();
    await expect(
      page.getByRole("button", { name: "Xóa tất cả hôm qua" }),
    ).toBeDisabled();
    await expect(runningCard).toBeVisible();
    await expect(
      page.locator(".interaction-card").filter({ hasText: "Today item" }),
    ).toBeVisible();
    expect(requests).toEqual([
      { method: "DELETE" },
      { method: "POST", date: "2026-11-10" },
    ]);
    expect(
      await page.evaluate(
        () => document.documentElement.scrollWidth <= window.innerWidth,
      ),
    ).toBe(true);
    await page.screenshot({
      path: `.data/screenshots/interaction-delete-${width}.png`,
      fullPage: true,
    });
  });
}
