import { randomUUID } from "node:crypto";
import { NextRequest } from "next/server";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { createAuth } from "../../src/lib/auth";
import { db } from "../../src/lib/db";
import {
  archiveInteraction,
  archiveYesterdayInteractions,
  interactionAction,
  listInteractions,
} from "../../src/lib/interactions";
import {
  autoInteractionSchema,
  autoInteractionStatus,
  saveAutoInteractions,
} from "../../src/lib/auto-interactions";
import { dateKey } from "../../src/lib/utils";
import {
  DELETE as deleteApi,
  POST as postApi,
} from "../../src/app/api/v1/[...path]/route";

const now = new Date("2026-11-11T00:30:00+07:00");
let workspaceId: string, otherWorkspaceId: string, accountId: string;
const ownerIds: string[] = [];
const cookies: string[] = [];

async function job(
  scheduledAt = new Date("2026-11-10T12:00:00+07:00"),
  data: { status?: string; autoGenerated?: boolean } = {},
) {
  const id = randomUUID();
  return db.interaction.create({
    data: {
      workspaceId,
      accountId,
      postUrl: `https://www.facebook.com/groups/fixture/posts/${id}`,
      postKey: `post:${id}`,
      kind: "COMBINED",
      reaction: "LIKE",
      reactionState: "PENDING",
      commentState: "PENDING",
      scheduledAt,
      ...data,
    },
  });
}

beforeAll(async () => {
  for (const suffix of ["owner", "other"]) {
    const result = await createAuth(true).api.signUpEmail({
      body: {
        name: `Archive ${suffix}`,
        email: `archive-${suffix}-${randomUUID()}@tests.nhipdang.local`,
        password: "Archive-tests-password-2026!",
      },
    });
    ownerIds.push(result.user.id);
    const response = await createAuth(true).api.signInEmail({
      body: {
        email: result.user.email,
        password: "Archive-tests-password-2026!",
      },
      asResponse: true,
    });
    cookies.push(
      response.headers
        .getSetCookie()
        .map((cookie) => cookie.split(";")[0])
        .join("; "),
    );
  }
  workspaceId = (
    await db.workspace.findUniqueOrThrow({ where: { ownerId: ownerIds[0] } })
  ).id;
  otherWorkspaceId = (
    await db.workspace.findUniqueOrThrow({ where: { ownerId: ownerIds[1] } })
  ).id;
  accountId = (
    await db.facebookAccount.create({
      data: {
        workspaceId,
        name: "Archive account",
        profileName: "Fixture",
        url: "https://facebook.com/fixture",
      },
    })
  ).id;
});

beforeEach(async () => {
  await db.interaction.deleteMany({ where: { workspaceId } });
  await db.autoInteractionSetting.deleteMany({ where: { workspaceId } });
});

afterAll(async () => {
  const workspaces = { in: [workspaceId, otherWorkspaceId] };
  await db.interaction.deleteMany({ where: { workspaceId: workspaces } });
  await db.task.deleteMany({ where: { workspaceId: workspaces } });
  await db.campaign.deleteMany({ where: { workspaceId: workspaces } });
  await db.user.deleteMany({ where: { id: { in: ownerIds } } });
  await db.$disconnect();
});

describe("deleting interaction work", () => {
  it("requires authentication, the correct workspace and Origin for both deletion routes", async () => {
    const row = await job();
    const request = (cookie: string, origin = "http://localhost:3000") =>
      new NextRequest(`http://localhost:3000/api/v1/interactions/${row.id}`, {
        method: "DELETE",
        headers: { Cookie: cookie, Origin: origin },
      });
    const context = {
      params: Promise.resolve({ path: ["interactions", row.id] }),
    };
    expect((await deleteApi(request(""), context)).status).toBe(401);
    expect((await deleteApi(request(cookies[1]), context)).status).toBe(404);
    expect(
      (await deleteApi(request(cookies[0], "https://other.example"), context))
        .status,
    ).toBe(403);
    expect((await deleteApi(request(cookies[0]), context)).status).toBe(200);
    const yesterday = new Date(Date.now() - 86_400_000);
    await job(yesterday);
    const bulkRequest = (cookie: string) =>
      new NextRequest(
        "http://localhost:3000/api/v1/interactions/delete-yesterday",
        {
          method: "POST",
          headers: {
            Cookie: cookie,
            Origin: "http://localhost:3000",
            "Content-Type": "application/json",
          },
          body: JSON.stringify({ date: dateKey(yesterday) }),
        },
      );
    const bulkContext = {
      params: Promise.resolve({ path: ["interactions", "delete-yesterday"] }),
    };
    expect((await postApi(bulkRequest(""), bulkContext)).status).toBe(401);
    const response = await postApi(bulkRequest(cookies[0]), bulkContext);
    expect(response.status).toBe(200);
    expect(await response.json()).toEqual({ archived: 1, running: 0 });
  });
  it("hides deleted work, stops pending steps and keeps its deduplication record", async () => {
    const row = await job(undefined, {
      status: "APPROVED",
      autoGenerated: true,
    });
    await db.interaction.update({
      where: { id: row.id },
      data: { reactionState: "COMPLETED" },
    });
    await expect(
      archiveInteraction(otherWorkspaceId, row.id),
    ).rejects.toMatchObject({ status: 404 });
    expect(await archiveInteraction(workspaceId, row.id)).toEqual({
      archived: 1,
    });
    const saved = await db.interaction.findUniqueOrThrow({
      where: { id: row.id },
    });
    expect(saved.archivedAt).not.toBeNull();
    expect(saved).toMatchObject({
      status: "SKIPPED",
      phase: "DONE",
      postKey: row.postKey,
      postUrl: row.postUrl,
      reactionState: "COMPLETED",
      commentState: "SKIPPED",
    });
    expect(
      (await listInteractions(workspaceId, new URLSearchParams(), now)).total,
    ).toBe(0);
    expect((await autoInteractionStatus(workspaceId, now)).counts).toEqual({});
    await expect(
      interactionAction(workspaceId, row.id, { action: "approve", note: "" }),
    ).rejects.toMatchObject({ status: 404 });
    expect(await archiveInteraction(workspaceId, row.id)).toEqual({
      archived: 0,
    });
    expect(
      await db.interactionEvent.count({ where: { interactionId: row.id } }),
    ).toBe(1);
  });

  it("keeps completed results and refuses to delete running work", async () => {
    const completed = await job(undefined, { status: "COMPLETED" });
    const running = await job(undefined, { status: "IN_PROGRESS" });
    await archiveInteraction(workspaceId, completed.id);
    expect(
      (await db.interaction.findUniqueOrThrow({ where: { id: completed.id } }))
        .status,
    ).toBe("COMPLETED");
    await expect(
      archiveInteraction(workspaceId, running.id),
    ).rejects.toMatchObject({ status: 409 });
    expect(
      (await db.interaction.findUniqueOrThrow({ where: { id: running.id } }))
        .archivedAt,
    ).toBeNull();
  });

  it("deletes all yesterday pages within UTC+7 boundaries and retains other workspaces and running work", async () => {
    const yesterdayStart = new Date("2026-11-09T17:00:00.000Z");
    const todayStart = new Date("2026-11-10T17:00:00.000Z");
    const rows = await Promise.all(Array.from({ length: 25 }, () => job()));
    const atStart = await job(yesterdayStart);
    const beforeStart = await job(new Date(yesterdayStart.getTime() - 1));
    const atEnd = await job(todayStart);
    const running = await job(undefined, { status: "IN_PROGRESS" });
    const otherAccount = await db.facebookAccount.create({
      data: {
        workspaceId: otherWorkspaceId,
        name: "Other",
        profileName: "Other",
        url: "https://facebook.com/other",
      },
    });
    const other = await db.interaction.create({
      data: {
        workspaceId: otherWorkspaceId,
        accountId: otherAccount.id,
        postKey: randomUUID(),
        postUrl: "https://facebook.com/other/posts/123",
        kind: "COMMENT",
        scheduledAt: yesterdayStart,
      },
    });
    const preview = await listInteractions(
      workspaceId,
      new URLSearchParams("size=1&status=COMPLETED"),
      now,
    );
    expect(preview.items).toHaveLength(0);
    expect(preview).toMatchObject({
      yesterdayDate: "2026-11-10",
      yesterdayCount: 26,
      yesterdayRunning: 1,
    });
    await expect(
      archiveYesterdayInteractions(workspaceId, "2026-11-09", now),
    ).rejects.toMatchObject({ status: 409 });
    expect(
      await archiveYesterdayInteractions(workspaceId, "2026-11-10", now),
    ).toEqual({ archived: 26, running: 1 });
    expect(
      await db.interaction.count({
        where: {
          id: { in: [...rows.map((row) => row.id), atStart.id] },
          archivedAt: { not: null },
        },
      }),
    ).toBe(26);
    expect(
      await db.interaction.count({
        where: {
          id: { in: [beforeStart.id, atEnd.id, running.id, other.id] },
          archivedAt: null,
        },
      }),
    ).toBe(4);
    expect(
      await archiveYesterdayInteractions(workspaceId, "2026-11-10", now),
    ).toEqual({ archived: 0, running: 1 });
  });

  it("does not recreate an archived automatic interaction when scanning the same source", async () => {
    const post = await db.post.create({
      data: { workspaceId, title: "Archived source", content: "Text" },
    });
    const campaign = await db.campaign.create({
      data: {
        workspaceId,
        postId: post.id,
        idempotencyKey: randomUUID(),
        requestHash: randomUUID(),
      },
    });
    const row = await job(undefined, { autoGenerated: true });
    const source = await db.task.create({
      data: {
        workspaceId,
        campaignId: campaign.id,
        postId: post.id,
        accountId,
        destinationKey: "PROFILE",
        titleSnapshot: "Archived source",
        contentSnapshot: "Text",
        contentHash: randomUUID(),
        scheduledAt: now,
        recordedAt: now,
        status: "PUBLISHED",
        resultUrl: row.postUrl,
      },
    });
    await db.interaction.update({
      where: { id: row.id },
      data: { sourceTaskId: source.id },
    });
    await archiveInteraction(workspaceId, row.id);
    const actor = await db.facebookAccount.create({
      data: {
        workspaceId,
        name: "Actor",
        profileName: "Actor",
        url: "https://facebook.com/actor",
      },
    });
    const device = await db.desktopDevice.create({
      data: { workspaceId, name: "Fixture device", tokenHash: randomUUID() },
    });
    await db.facebookConnection.create({
      data: {
        workspaceId,
        accountId: actor.id,
        deviceId: device.id,
        state: "READY",
        interactionEnabled: true,
        identityHash: "a".repeat(64),
        confirmedIdentityHash: "a".repeat(64),
      },
    });
    const result = await saveAutoInteractions(
      workspaceId,
      autoInteractionSchema.parse({
        enabled: true,
        mode: "COMMENT",
        content: "Fixture",
        reactions: [],
        selectedDays: ["TODAY"],
        version: 0,
      }),
      now,
    );
    expect(result.queued).toBe(0);
    expect(result.settings.backfillDays.map((day) => dateKey(day))).toEqual([
      "2026-11-11",
    ]);
    expect(await db.interaction.count({ where: { workspaceId } })).toBe(1);
    expect((await autoInteractionStatus(workspaceId, now)).waitingSources).toBe(
      0,
    );
  });
});
