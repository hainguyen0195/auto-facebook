CREATE TABLE "AutoInteractionSetting" (
  "workspaceId" TEXT NOT NULL PRIMARY KEY,
  "enabled" BOOLEAN NOT NULL DEFAULT false,
  "mode" TEXT NOT NULL DEFAULT 'COMBINED',
  "content" TEXT NOT NULL DEFAULT 'Up',
  "reactions" TEXT[] NOT NULL DEFAULT ARRAY['LIKE','LOVE','HAHA']::TEXT[],
  "startsAt" TIMESTAMP(3),
  "lastActorId" TEXT,
  "version" INTEGER NOT NULL DEFAULT 1,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "AutoInteractionSetting_workspaceId_fkey" FOREIGN KEY ("workspaceId") REFERENCES "Workspace"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
ALTER TABLE "Interaction"
  ADD COLUMN "autoGenerated" BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN "reactionState" TEXT NOT NULL DEFAULT 'NONE',
  ADD COLUMN "commentState" TEXT NOT NULL DEFAULT 'NONE';
CREATE INDEX "Task_workspaceId_status_recordedAt_idx" ON "Task"("workspaceId", "status", "recordedAt");
CREATE INDEX "Interaction_workspaceId_autoGenerated_status_idx" ON "Interaction"("workspaceId", "autoGenerated", "status");
UPDATE "Interaction" SET
  "reactionState" = CASE WHEN "kind" = 'REACTION' THEN CASE
    WHEN "status" = 'COMPLETED' THEN 'COMPLETED'
    WHEN "status" IN ('SKIPPED','FAILED','NEEDS_REVIEW') THEN "status"
    WHEN "status" = 'IN_PROGRESS' AND "phase" = 'SUBMITTING' THEN 'SUBMITTING'
    ELSE 'PENDING' END ELSE 'NONE' END,
  "commentState" = CASE WHEN "kind" IN ('COMMENT','BUMP') THEN CASE
    WHEN "status" = 'COMPLETED' THEN 'COMPLETED'
    WHEN "status" IN ('SKIPPED','FAILED','NEEDS_REVIEW') THEN "status"
    WHEN "status" = 'IN_PROGRESS' AND "phase" = 'SUBMITTING' THEN 'SUBMITTING'
    ELSE 'PENDING' END ELSE 'NONE' END;
