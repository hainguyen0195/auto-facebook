ALTER TABLE "AutoInteractionSetting"
  ADD COLUMN "backfillDays" TIMESTAMP(3)[] NOT NULL DEFAULT ARRAY[]::TIMESTAMP(3)[],
  ADD COLUMN "gapMinutes" INTEGER NOT NULL DEFAULT 5;

CREATE INDEX "Interaction_workspaceId_executionMode_startedAt_idx"
  ON "Interaction"("workspaceId", "executionMode", "startedAt");

-- Stagger existing waiting work; do not touch a run already in progress.
WITH pending AS (
  SELECT id,
    SUM(CASE WHEN kind = 'COMBINED' AND "reactionState" <> 'COMPLETED' THEN 2 ELSE 1 END)
      OVER (PARTITION BY "workspaceId" ORDER BY "scheduledAt", id ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS slots
  FROM "Interaction"
  WHERE "autoGenerated" = TRUE AND status IN ('APPROVED', 'RETRY_WAIT', 'PLANNED')
)
UPDATE "Interaction" AS job
SET "scheduledAt" = GREATEST(job."scheduledAt", CURRENT_TIMESTAMP)
    + (COALESCE(pending.slots, 0) + 1) * INTERVAL '5 minutes',
    version = job.version + 1
FROM pending WHERE pending.id = job.id;
